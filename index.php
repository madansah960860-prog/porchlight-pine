            <h2 id="story-title">How this started</h2>
          </div>
          <p>Porchlight &amp; Pine began as a stall at a Saturday market on Haywood Road, selling cedar
             feeders that one of us had been building in a garage for years. People kept asking the same
             two questions — what wood is it, and how do I clean it — and it turned out that answering
             those honestly was most of the business.</p>
          <p>So that is the shop. A short list of things for the yard and the front step, each one with
             its material, its measurements and its cleaning instructions written out. We are not the
             cheapest and we are not trying to be. We would rather sell you one feeder that lasts ten
             seasons than three that last one each.</p>
